"""Human reports — "kya bacha hai" in one markdown file per subject.

Written to ``state/reports/<key>.md`` and a combined ``_SYNC-STATUS.md`` at the
library root so the founder can open the drive on any PC and see the state.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

from .config import free_space_gb
from .layout import Layout
from .plan import ALL_KINDS

KIND_LABEL = {
    "videos": "Videos",
    "notes": "Notes",
    "dpp": "DPP",
    "slides": "Slides",
    "documents": "E-books",
}


def _cell_text(text: str) -> str:
    """Chapter names can contain ``|`` (``E-Book || PDF Only``); a table cell cannot."""
    return str(text or "").replace("|", "\\|")


def _cell(counts: dict) -> str:
    done = counts.get("done", 0)
    total = counts.get("total", 0)
    if counts.get("unavailable"):
        total -= counts["unavailable"]
    if total == 0:
        return "—"
    mark = "✅" if done >= total else "⚠️"
    return f"{mark} {done}/{total}"


def render_subject(record: dict, plan: dict) -> str:
    summary = plan["summary"]
    lines = [
        f"# {record.get('subject_name', plan.get('subject', {}).get('name', 'Subject'))}",
        "",
        f"- Batch: **{record.get('batch_name', '')}**",
        f"- Folder: `{plan['root']}`",
        f"- Catalog: {plan.get('catalog_at', '') or '—'}",
        f"- Report date: {date.today().isoformat()}",
        f"- Disk free: {plan.get('free_gb', '?')} GB",
        "",
        "## Summary",
        "",
        "| | Total | Done | Missing |",
        "|---|---|---|---|",
        f"| Videos | {summary['by_kind']['videos']['total']} | {summary['by_kind']['videos']['done']} "
        f"| {summary['by_kind']['videos']['missing']} |",
        f"| Notes | {summary['by_kind']['notes']['total']} | {summary['by_kind']['notes']['done']} "
        f"| {summary['by_kind']['notes']['missing']} |",
        f"| DPP | {summary['by_kind']['dpp']['total']} | {summary['by_kind']['dpp']['done']} "
        f"| {summary['by_kind']['dpp']['missing']} |",
        f"| Slides | {summary['by_kind']['slides']['total']} | {summary['by_kind']['slides']['done']} "
        f"| {summary['by_kind']['slides']['missing']} |",
        f"| E-books | {summary['by_kind']['documents']['total']} | {summary['by_kind']['documents']['done']} "
        f"| {summary['by_kind']['documents']['missing']} |",
        "",
        "## Chapters",
        "",
        "| Chapter | Videos | Notes | DPP | Slides | E-books |",
        "|---|---|---|---|---|---|",
    ]
    for chapter in plan["chapters"]:
        counts = {kind: _kind_counts(chapter["items"], kind) for kind in ALL_KINDS}
        lines.append(
            f"| {_cell_text(chapter['name'])} | {_cell(counts['videos'])} | {_cell(counts['notes'])} "
            f"| {_cell(counts['dpp'])} | {_cell(counts['slides'])} | {_cell(counts['documents'])} |"
        )
    missing = [item for item in plan["items"] if item["status"] == "missing"]
    lines += ["", "## Missing (first 40)", ""]
    if not missing:
        lines.append("Sab kuch local me hai. 🎉")
    else:
        for item in missing[:40]:
            label = KIND_LABEL.get(item["kind"], item["kind"])
            lines.append(f"- [{label}] {item['chapter']} → {item['name']}")
        if len(missing) > 40:
            lines.append(f"- … aur {len(missing) - 40} items (UI me poora list)")
    lines.append("")
    return "\n".join(lines)


def _kind_counts(items: list[dict], kind: str) -> dict:
    subset = [item for item in items if item["kind"] == kind]
    counts = {"total": len(subset), "done": 0, "missing": 0, "unavailable": 0}
    for item in subset:
        counts[item["status"]] = counts.get(item["status"], 0) + 1
    return counts


def render_library(rows: list[tuple[dict, dict]], output_root: Path) -> str:
    lines = [
        "# CA Inter — offline sync status",
        "",
        f"Updated: {date.today().isoformat()} · free space: {free_space_gb(output_root) or '?'} GB",
        "",
        "| Subject | Videos | Notes | DPP | Slides | E-books | Folder |",
        "|---|---|---|---|---|---|---|",
    ]
    for record, plan in rows:
        summary = plan["summary"]["by_kind"]
        lines.append(
            "| {name} | {v} | {n} | {d} | {s} | {e} | `{folder}` |".format(
                name=record.get("subject_name", record.get("key", "")),
                v=_cell(summary["videos"]), n=_cell(summary["notes"]),
                d=_cell(summary["dpp"]), s=_cell(summary["slides"]),
                e=_cell(summary["documents"]),
                folder=Path(plan["root"]).name,
            )
        )
    lines += [
        "",
        "Legend: ✅ complete · ⚠️ kuch bacha hai · — is subject me nahi hai",
        "",
        "Generated by Video-Downloader (`python -m vd status --all`). Videos aur PDFs isi",
        "folder structure me rehte hain; kuch bhi move karne ki zarurat nahi.",
        "",
    ]
    return "\n".join(lines)


def write_subject_report(record: dict, plan: dict, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_subject(record, plan), encoding="utf-8")
    return path


def write_library_status(rows: list[tuple[dict, dict]], output_root: Path) -> Path:
    Layout.ensure(Path(output_root))
    path = Path(output_root) / "_SYNC-STATUS.md"
    path.write_text(render_library(rows, output_root), encoding="utf-8")
    return path
